async function assertReferences() {
  const npcIds = unique([
    ...profiles.map((entry) => entry.npcId),
    ...relationships.flatMap((entry) => [entry.npcAId, entry.npcBId]),
    ...memories.map((entry) => entry.npcId),
    ...memories.flatMap((entry) => entry.relatedNpcIds || []),
  ]);
  const existing = await Npc.find({ npcId: { $in: npcIds } }).distinct("npcId");
  const missing = npcIds.filter((npcId) => !existing.includes(npcId));

  if (missing.length) {
    throw new Error(`Missing NPCs for living layer seed: ${missing.join(", ")}`);
  }
}

async function seedHoshimoriNpcLivingLayer() {
  await connectDB();

  if (mongoose.connection.readyState !== 1) {
    throw new Error("MONGODB_URI is required to seed Hoshimori NPC living layer.");
  }

  await assertReferences();

  await Npc.bulkWrite(
    profiles.map((entry) => ({
      updateOne: {
        filter: { npcId: entry.npcId },
        update: {
          $set: {
            socialProfile: entry.socialProfile,
            "flags.livingLayer": entry.livingLayer,
            "flags.livingLayerSource": SOURCE,
          },
        },
      },
    })),
    { ordered: false }
  );

  await NpcRelationship.bulkWrite(
    relationships.map((entry) => ({
      updateOne: {
        filter: { npcAId: entry.npcAId, npcBId: entry.npcBId },
        update: { $set: entry },
        upsert: true,
      },
    })),
    { ordered: false }
  );

  await NpcMemory.bulkWrite(
    memories.map((entry) => ({
      updateOne: {
        filter: { memoryId: entry.memoryId },
        update: { $set: entry },
        upsert: true,
      },
    })),
    { ordered: false }
  );

  const [profileCount, relationshipCount, memoryCount] = await Promise.all([
    Npc.countDocuments({ "flags.livingLayerSource": SOURCE }),
    NpcRelationship.countDocuments({ source: SOURCE }),
    NpcMemory.countDocuments({ sourceId: SOURCE }),
  ]);

  console.log("Hoshimori NPC living layer seed completed.");
  console.log(`NPC profiles updated: ${profileCount}`);
  console.log(`NPC relationships with source ${SOURCE}: ${relationshipCount}`);
  console.log(`NPC memories with source ${SOURCE}: ${memoryCount}`);

  await mongoose.disconnect();
}

if (require.main === module) {
  seedHoshimoriNpcLivingLayer().catch(async (error) => {
    console.error("Error seeding Hoshimori NPC living layer:", error.message);
    await mongoose.disconnect();
    process.exit(1);
  });
}

