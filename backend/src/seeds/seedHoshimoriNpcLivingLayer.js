function unique(values = []) {
  return Array.from(new Set(values.filter(Boolean)));
}

function normalizePair(left, right) {
  return [left, right].sort();
}

function profile(npcId, data) {
  return {
    npcId,
    socialProfile: {
      archetype: data.archetype,
      affinityTags: data.affinityTags || [],
      frictionTags: data.frictionTags || [],
      trustSignals: data.trustSignals || [],
      respectSignals: data.respectSignals || [],
      affectionSignals: data.affectionSignals || [],
      suspicionSignals: data.suspicionSignals || [],
      fearSignals: data.fearSignals || [],
      jealousySignals: data.jealousySignals || [],
      boundaries: data.boundaries || [],
      notes: `source:${SOURCE}; ${data.notes || ""}`.trim(),
    },
    livingLayer: {
      schemaVersion: "npc_living_layer_v1",
      currentConcern: data.currentConcern || "",
      personalGoals: data.personalGoals || [],
      agencyHooks: data.agencyHooks || [],
      dialogueExample: data.dialogueExample || "",
      dialogueTexture: data.dialogueTexture || "",
      scenePressure: data.scenePressure || "",
      source: SOURCE,
    },
  };
}

function relationship(left, right, data) {
  const [npcAId, npcBId] = normalizePair(left, right);
  return {
    relationshipId: `rel_${npcAId}_${npcBId}`,
    npcAId,
    npcBId,
    type: data.type,
    trust: data.trust,
    familiarity: data.familiarity,
    tension: data.tension,
    publicSummary: data.publicSummary,
    privateNotes: data.privateNotes || "",
    emotionalTone: data.emotionalTone || "",
    publicTensionReason: data.publicTensionReason || "",
    privateSubtext: data.privateSubtext || "",
    interactionHints: data.interactionHints || [],
    boundaries: data.boundaries || [],
    knownToLucas: data.knownToLucas ?? false,
    source: SOURCE,
    tags: unique([...MARKER_TAGS, SOURCE, ...(data.tags || [])]),
  };
}

function memory(memoryId, npcId, data) {
  return {
    memoryId,
    npcId,
    fact: data.fact,
    summary: data.summary,
    sourceType: data.sourceType || "saw",
    sourceId: SOURCE,
    certainty: data.certainty || "confirmed",
    emotionalWeight: data.emotionalWeight || "low",
    privacyLevel: data.privacyLevel || "semi_private",
    canShare: data.canShare ?? false,
    shareConditions: data.shareConditions || [],
    createdDay: data.createdDay || CREATED_DAY,
    createdTime: data.createdTime || CREATED_TIME,
    lastReferencedDay: data.lastReferencedDay || null,
    importance: data.importance || "normal",
    decayType: data.decayType || "none",
    relatedNpcIds: data.relatedNpcIds || [],
    relatedLocationIds: data.relatedLocationIds || [],
    tags: unique([...MARKER_TAGS, SOURCE, ...(data.tags || [])]),
  };
}

